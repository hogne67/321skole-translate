function normalizeSound(value: string): string {
  return value.trim().toLocaleLowerCase();
}

function normalizeWord(value: string): string {
  return value.trim().toLocaleLowerCase();
}

export function getNorwegianSoundWordEntries(sound: string): SoundWordEntry[] {
  return NORWEGIAN_SOUND_WORD_BANKS[normalizeSound(sound)]?.words ?? [];
}

export function getNorwegianSoundWords(sound: string, count: number): string[] {
  if (count <= 0) return [];
  const entries = getNorwegianSoundWordEntries(sound);
  return entries.slice(0, count).map((item) => item.word);
}

export function getNorwegianInsideSoundWords(sound: string): string[] {
  return getNorwegianSoundWordEntries(sound)
    .filter((item) => item.position === "inside")
    .map((item) => item.word);
}

export function isApprovedNorwegianSoundWord(sound: string, word: string): boolean {
  const normalizedWord = normalizeWord(word);
  return getNorwegianSoundWordEntries(sound).some((item) => normalizeWord(item.word) === normalizedWord);
}

export function norwegianSoundWordStartsWithSound(sound: string, word: string): boolean {
  const normalizedWord = normalizeWord(word);
  const normalizedSound = normalizeSound(sound);
  const entry = getNorwegianSoundWordEntries(sound).find((item) => normalizeWord(item.word) === normalizedWord);
  if (entry) return entry.position === "initial";
  return normalizedWord.startsWith(normalizedSound);
}

export function norwegianSoundWordContainsSound(sound: string, word: string): boolean {
  const normalizedWord = normalizeWord(word);
  const normalizedSound = normalizeSound(sound);
  return isApprovedNorwegianSoundWord(sound, word) || normalizedWord.includes(normalizedSound);
}

export function getNorwegianSoundBank(sound: string): SoundWordBank | null {
  return NORWEGIAN_SOUND_WORD_BANKS[normalizeSound(sound)] ?? null;
}
