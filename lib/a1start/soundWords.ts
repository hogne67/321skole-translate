export type SoundWordPosition = "initial" | "inside";
export type SoundWordLevel = "core" | "extra";
export type SoundRisk = "safe" | "sensitive";

export type SoundWordEntry = {
  word: string;
  position: SoundWordPosition;
  level: SoundWordLevel;
};

export type SoundWordBank = {
  risk: SoundRisk;
  notes?: string;
  words: SoundWordEntry[];
};

function entry(word: string, position: SoundWordPosition, level: SoundWordLevel = "core"): SoundWordEntry {
  return { word, position, level };
}

